# Completes Firebase setup for sleek-btg-studio after you accept Firebase terms in the Console.
# Usage (PowerShell):
#   .\firebase\provision.ps1

$ErrorActionPreference = "Stop"
$projectId = "sleek-btg-studio"
$account = "rachellaperez143@gmail.com"
$root = Resolve-Path (Join-Path $PSScriptRoot "..")

Write-Host "Using project $projectId"
gcloud config set account $account | Out-Null
gcloud config set project $projectId | Out-Null

gcloud services enable `
  firebase.googleapis.com `
  firestore.googleapis.com `
  identitytoolkit.googleapis.com `
  storage.googleapis.com `
  firebasehosting.googleapis.com `
  --project=$projectId

$token = gcloud auth print-access-token --account=$account
$headers = @(
  "-H", "Authorization: Bearer $token",
  "-H", "x-goog-user-project: $projectId",
  "-H", "Content-Type: application/json"
)

Write-Host "Linking Firebase to GCP project..."
$add = curl.exe -sS -X POST "https://firebase.googleapis.com/v1beta1/projects/${projectId}:addFirebase" @headers -d "{}"
Write-Host $add
if ($add -match "PERMISSION_DENIED") {
  Write-Host ""
  Write-Host "Open this URL while logged in as $account, accept Firebase terms, then re-run this script:"
  Write-Host "https://console.firebase.google.com/?pli=1"
  Write-Host "Then click Add project → use existing Google Cloud project → $projectId"
  exit 1
}

# Wait until Firebase project is visible
for ($i = 0; $i -lt 12; $i++) {
  $get = curl.exe -sS "https://firebase.googleapis.com/v1beta1/projects/$projectId" @headers
  if ($get -match '"projectId"') { break }
  Start-Sleep -Seconds 3
}

Write-Host "Creating web app..."
$webBody = '{"displayName":"Sleek.btg Site"}'
$webCreate = curl.exe -sS -X POST "https://firebase.googleapis.com/v1beta1/projects/$projectId/webApps" @headers -d $webBody
Write-Host $webCreate

# Operation name may be returned; poll web apps list
$appId = $null
for ($i = 0; $i -lt 15; $i++) {
  $apps = curl.exe -sS "https://firebase.googleapis.com/v1beta1/projects/$projectId/webApps" @headers
  if ($apps -match '"appId":\s*"([^"]+)"') {
    $appId = $Matches[1]
    break
  }
  Start-Sleep -Seconds 2
}
if (-not $appId) { throw "Web app was not created. Check Firebase Console → Project settings." }

Write-Host "Fetching SDK config for $appId ..."
$configJson = curl.exe -sS "https://firebase.googleapis.com/v1beta1/projects/$projectId/webApps/$appId/config" @headers
$config = $configJson | ConvertFrom-Json

$configPath = Join-Path $root "js\firebase\config.js"
$configJs = @"
/**
 * Auto-generated by firebase/provision.ps1
 */
export const firebaseConfig = {
  apiKey: '$($config.apiKey)',
  authDomain: '$($config.authDomain)',
  projectId: '$($config.projectId)',
  storageBucket: '$($config.storageBucket)',
  messagingSenderId: '$($config.messagingSenderId)',
  appId: '$($config.appId)',
};

export function isFirebaseConfigured() {
  return Boolean(firebaseConfig.apiKey && firebaseConfig.projectId);
}
"@
Set-Content -Path $configPath -Value $configJs -Encoding UTF8
Write-Host "Wrote $configPath"

Write-Host "Creating Firestore database (nam5)..."
# Native mode Firestore
curl.exe -sS -X POST "https://firestore.googleapis.com/v1/projects/$projectId/databases?databaseId=(default)" `
  -H "Authorization: Bearer $token" `
  -H "x-goog-user-project: $projectId" `
  -H "Content-Type: application/json" `
  -d '{"type":"FIRESTORE_NATIVE","locationId":"nam5"}'

Write-Host ""
Write-Host "Done with API provisioning."
Write-Host "Manual finish (2 minutes in Console):"
Write-Host "1) Authentication → Sign-in method → Email/Password → Enable"
Write-Host "2) Authentication → Users → Add user (your admin email/password)"
Write-Host "3) Firestore → Rules → paste firebase/firestore.rules → Publish"
Write-Host "4) Storage → Get started → Rules → paste firebase/storage.rules → Publish"
Write-Host "5) Open http://localhost:8765/admin/ and sign in"
